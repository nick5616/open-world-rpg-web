// courseGround is the TS golden's `course` (client/src/sim/golden/ride.ts
// COURSE): a hill, a plateau with a 10 m drop, a cliff, a ford, a lake with a
// sloping bank, a fence, and one solid building wall. Same arithmetic, same
// doubles; the box numbers are run-time values (not Go constants) so their
// sums round like V8's.
type courseGround struct{ box courseBox }

type courseBox struct{ x0, x1, z0, z1, top, r float64 }

func newCourse() courseGround {
	return courseGround{courseBox{1060, 1062, 900, 1040, 4, 0.4}}
}

func courseBase(z float64) float64 {
	switch {
	case z > 1040:
		return (z - 1040) * 2
	case z > 940:
		return 0
	case z > 920:
		return (940 - z) * 0.5
	case z > 880:
		return 10
	}
	return 0
}

func (courseGround) HeightAt(x, z float64) float64 {
	h := courseBase(z)
	switch {
	case x < 955:
		h -= 2.2
	case x < 960:
		h -= 0.9 + (960-x)*0.26
	case x < 975:
		h -= 0.9
	}
	if x >= 1040 && x < 1040.6 {
		h += 1
	}
	return h
}

func (courseGround) WaterAt(x, _ float64) float64 {
	if x < 975 {
		return -0.5
	}
	return math.Inf(-1)
}

func (c courseGround) Collide(x, y, z float64) CollideResult {
	out := CollideResult{X: x, Y: y, Z: z}
	b := c.box
	if y >= b.top || x <= b.x0-b.r || x >= b.x1+b.r || z <= b.z0-b.r || z >= b.z1+b.r {
		return out
	}
	dl := x - (b.x0 - b.r)
	dr := b.x1 + b.r - x
	dn := z - (b.z0 - b.r)
	ds := b.z1 + b.r - z
	m := math.Min(math.Min(dl, dr), math.Min(dn, ds))
	switch m {
	case dl:
		out.X = b.x0 - b.r
	case dr:
		out.X = b.x1 + b.r
	case dn:
		out.Z = b.z0 - b.r
	default:
		out.Z = b.z1 + b.r
	}
	out.PushX, out.PushZ = out.X-x, out.Z-z
	return out
}

// TestReplaysRideGoldens replays CR 027's riding trajectories generated by
// the TS step (client/src/sim/golden/ride.ts) through this step: positions
// within 1e-9 m and the whole discrete state (mode, stamina, timer, the gait
// bits in lunge, the mounted/sliding flags) exactly.
func TestReplaysRideGoldens(t *testing.T) {
	dir := filepath.Join("..", "..", "..", "client", "src", "sim", "golden")
	for _, name := range []string{"movement_pt2_ride_flat.json", "movement_pt2_ride_plane.json", "movement_pt2_ride_course_east.json", "movement_pt2_ride_course_west.json"} {
		raw, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Skipf("client goldens not available: %v", err)
		}
		var g struct {
			Ground struct {
				Kind                 string
				Height, Base, Sx, Sz float64
			} `json:"ground"`
			Initial [12]float64   `json:"initial"`
			Frames  [][5]float64  `json:"frames"`
			States  [][12]float64 `json:"states"`
		}
		if err := json.Unmarshal(raw, &g); err != nil {
			t.Fatal(err)
		}
		var ground Ground = Flat{Y: g.Ground.Height}
		switch g.Ground.Kind {
		case "plane":
			ground = plane{g.Ground.Base, g.Ground.Sx, g.Ground.Sz}
		case "course":
			ground = newCourse()
		}
		in := g.Initial
		s := NewState(Vec3{in[0], in[1], in[2]})
		s.Flags = uint8(in[11])
		mountedSteps, dismounts := 0, 0
		for i, f := range g.Frames {
			prev := s
			s = StepFrame(s, proto.InputFrame{Seq: uint32(f[0]), Flags: uint16(f[1]), Yaw: uint16(f[2]), Pitch: int16(f[3]), CastSlot: uint8(f[4])}, ground)
			w := g.States[i]
			got := [12]float64{s.Pos.X, s.Pos.Y, s.Pos.Z, s.Vel.X, s.Vel.Y, s.Vel.Z, float64(s.AirJumps), float64(s.Mode), float64(s.Stamina), float64(s.Timer), float64(s.Lunge), float64(s.Flags)}
			for k := range got {
				tol := 1e-9
				if k >= 6 {
					tol = 0
				}
				if math.Abs(got[k]-w[k]) > tol {
					t.Fatalf("%s frame %d field %d: go %v vs ts %v", name, i, k, got[k], w[k])
				}
			}
			if Mounted(s) {
				mountedSteps++
				// Every legit riding step passes the zone's bounds.
				if HorizontalSpeed(s) > MaxHorizontalSpeed(prev, s) {
					t.Fatalf("%s frame %d: speed %v over bound %v", name, i, HorizontalSpeed(s), MaxHorizontalSpeed(prev, s))
				}
			}
			if Mounted(prev) && !Mounted(s) {
				dismounts++
			}
		}
		if mountedSteps < 300 || dismounts != 1 {
			t.Fatalf("%s: %d mounted steps, %d dismounts", name, mountedSteps, dismounts)
		}
	}
}

func rider(x, z float64) State {
	return Mount(NewState(Vec3{x, 0, z}))
}

func runRide(s State, n int, flags uint16, yaw float64, g Ground) State {
	for i := 0; i < n; i++ {
		s = Step(s, flags, yaw, g)
	}
	return s
}

// TestRideGaitsAndSpurs: W trots, a Shift press spurs to a gallop and costs
// RIDE_SPUR_STAMINA, holding Shift does not spur again, a second spur bursts
// under the cap and fades back to the gallop.
func TestRideGaitsAndSpurs(t *testing.T) {
	g := Flat{}
	s := runRide(rider(100, 100), 120, proto.InputFlagForward, 0, g)
	if math.Abs(HorizontalSpeed(s)-constants.RideTrotSpeed) > 1e-9 {
		t.Fatalf("trot %v", HorizontalSpeed(s))
	}
	s = Step(s, proto.InputFlagForward|proto.InputFlagSprint, 0, g)
	if s.Lunge&3 != GaitGallop || s.Stamina != s.StaminaMax-SpurCost {
		t.Fatalf("spur: gait %d stamina %d", s.Lunge&3, s.Stamina)
	}
	s = runRide(s, 40, proto.InputFlagForward|proto.InputFlagSprint, 0, g)
	if s.Stamina != s.StaminaMax-SpurCost {
		t.Fatal("held Shift spurred again")
	}
	s = runRide(s, 60, proto.InputFlagForward, 0, g)
	s = Step(s, proto.InputFlagForward|proto.InputFlagSprint, 0, g)
	if sp := HorizontalSpeed(s); sp <= constants.RideGallopSpeed+4 || sp > constants.RideSpurMaxSpeed {
		t.Fatalf("burst %v", sp)
	}
	s = runRide(s, 240, proto.InputFlagForward, 0, g)
	if math.Abs(HorizontalSpeed(s)-constants.RideGallopSpeed) > 1e-9 {
		t.Fatalf("burst did not fade: %v", HorizontalSpeed(s))
	}
}

// TestRideNeverMountsItself: the step only ever clears FlagMounted (only
// the zone sets it), and a dodge or held dash does nothing while riding.
func TestRideNeverMountsItself(t *testing.T) {
	s := NewState(Vec3{100, 0, 100})
	for i := 0; i < 2000; i++ {
		s = Step(s, uint16(i*2654435761)&0x7fff, float64(i)*0.01, Flat{})
		if Mounted(s) {
			t.Fatalf("step %d mounted itself", i)
		}
	}
	r := runRide(rider(100, 100), 30, proto.InputFlagForward, 0, Flat{})
	d := StepFrame(r, proto.InputFrame{Flags: proto.InputFlagForward | proto.InputFlagDodge, CastSlot: 1}, Flat{})
	if d.Dash != 0 || d.IFrames != 0 || !Mounted(d) {
		t.Fatalf("a rider dashed: %+v", d)
	}
}

// TestRideValidationOnlyWhileMounted: a gallop is a legit step in the saddle
// and a violation on foot (anti speed hack: the flag is the zone's alone),
// while an honest on-foot sprint and a dismount at a gallop pass.
func TestRideValidationOnlyWhileMounted(t *testing.T) {
	g := Flat{}
	s := runRide(rider(100, 100), 120, proto.InputFlagForward, 0, g)
	s = Step(s, proto.InputFlagForward|proto.InputFlagSprint, 0, g)
	s = runRide(s, 90, proto.InputFlagForward, 0, g)
	prev := s
	next := Step(prev, proto.InputFlagForward, 0, g)
	if HorizontalSpeed(next) > MaxHorizontalSpeed(prev, next) {
		t.Fatalf("mounted gallop refused: %v > %v", HorizontalSpeed(next), MaxHorizontalSpeed(prev, next))
	}
	// The same motion without the flag: from a walk to a gallop in one step.
	walk := runRide(NewState(Vec3{100, 0, 100}), 120, proto.InputFlagForward, 0, g)
	forged := walk
	forged.Pos.Z -= constants.RideGallopSpeed * Dt
	forged.Vel = Vec3{0, 0, -constants.RideGallopSpeed}
	if HorizontalSpeed(forged) <= MaxHorizontalSpeed(walk, forged) {
		t.Fatalf("a gallop on foot passed: bound %v", MaxHorizontalSpeed(walk, forged))
	}
	// A burst over the spur cap is refused even in the saddle.
	over := next
	over.Vel = Vec3{0, 0, -(constants.RideSpurMaxSpeed + 1)}
	if HorizontalSpeed(over) <= MaxHorizontalSpeed(prev, over) {
		t.Fatal("a ride over the spur cap passed")
	}
	// Honest sprinting on foot passes the tighter on-foot bound every step.
	f := NewState(Vec3{100, 0, 100})
	for i := 0; i < 300; i++ {
		n := Step(f, proto.InputFlagForward|proto.InputFlagSprint, float64(i)*0.02, g)
		if HorizontalSpeed(n) > MaxHorizontalSpeed(f, n) {
			t.Fatalf("sprint step %d refused", i)
		}
		f = n
	}
	// Dismounted at a gallop (E: the zone clears the flag): friction slows you, never a violation.
	d := Dismount(next)
	for i := 0; i < 60; i++ {
		n := Step(d, proto.InputFlagForward, 0, g)
		if HorizontalSpeed(n) > MaxHorizontalSpeed(d, n) {
			t.Fatalf("after dismount step %d refused", i)
		}
		d = n
	}
}

// TestRideCantClimbOrSwim: a mounted state in a mode a rider can't be in
// loses the flag; a rider walking into a lake stops at the wading depth.
func TestRideCantClimbOrSwim(t *testing.T) {
	s := rider(100, 100)
	s.Mode = ModeSwim
	if Mounted(Step(s, 0, 0, Flat{})) {
		t.Fatal("a swimmer stayed mounted")
	}
	c := newCourse()
	r := Mount(NewState(Vec3{985, c.HeightAt(985, 1000), 1000}))
	r = runRide(r, 900, proto.InputFlagForward, math.Pi/2, c)
	if !Mounted(r) || WaterAt(c, r.Pos.X, r.Pos.Z)-c.HeightAt(r.Pos.X, r.Pos.Z) >= constants.RideWadeDepthM || HorizontalSpeed(r) != 0 {
		t.Fatalf("the steed did not refuse the lake: %+v", r)
	}
}
