// Package items is the zone's item logic (WP14, spec 8 "Loot, rarities and
// dropping items", spec 7 gems and ores): the item record every grant,
// drop, craft and trade moves around, the seeded rolls (rarity with luck,
// affixes keyed by element and loot theme, uniques, sockets), the loot
// tables for kills, bosses and containers, the inventory (40 slots, a gem
// pouch, an ore pouch, a purse, equipment) with stacking, socketing, gem
// combining, smelting/forging/cooking, and the gear stats combat reads.
//
// Everything here is pure and tick-owned: no I/O, no clocks (callers pass
// times and seeds), no goroutines. Every inventory operation records what
// it changed in a Delta, which the game package turns into ONE ordered
// Postgres transaction (internal/game/items_journal.go) so the database
// always holds a prefix of the zone's history: a crash loses a suffix,
// never duplicates an item.
//
// Numbers come from contracts/items.yaml through server/pkg/itemdefs.
package items

import (
	"crypto/rand"
	"encoding/hex"
	"encoding/json"
	"strconv"
	"strings"

	"lodestone/server/pkg/itemdefs"
)

// D is the item table.
var D = itemdefs.D

// Affix is one rolled stat line on an item.
type Affix struct {
	Key   string  `json:"k"`
	Stat  string  `json:"s"`
	Value float64 `json:"v"`
}

// Prov is one provenance entry (spec 8: "who rolled it and every hand it
// has passed through"). Ev: rolled, crafted, starter, purchased, dropped,
// picked_up, split, local_upgrade.
type Prov struct {
	Ev    string `json:"ev"`
	Char  string `json:"char,omitempty"`
	Name  string `json:"name,omitempty"`
	Src   string `json:"src,omitempty"`   // grant key, recipe, reason
	At    int64  `json:"at,omitempty"`    // unix ms
	Local bool   `json:"local,omitempty"` // done by a local profile (unverified)
}

// Item is one item or stack. The zone's copy is authoritative while the
// owner is online (spec 11); Postgres (items table) is the checkpoint.
type Item struct {
	ID        string   // uuid, generated by the zone (idempotent inserts)
	H         uint32   // wire handle, zone-local (Interact targetId)
	Base      string   // itemdefs key, e.g. weapon:sunsteel_blade
	Qty       int      // stack size, >= 1
	Level     int      // item level
	Rarity    int      // 0 common .. 7 Bitchin'
	Affixes   []Affix  // rolled stat lines
	Uniques   []string // unique effect keys (legendary+)
	Name      string   // generated name (mythic+), "" otherwise
	Sockets   []string // one entry per socket: "" empty or a gem key
	Slot      string   // inv:N, gem:N, ore:N, purse, eq:main0|main1|head|body|legs; "" in the world
	Seed      int64    // the roll seed (spec 8: logged for audit)
	Tradeable bool
	Verified  bool
	Prov      []Prov
}

// Def is the base item definition (never nil for items the zone created).
func (it *Item) Def() *itemdefs.Item { return D.Item(it.Base) }

// Clone deep-copies an item (DB ops snapshot items at enqueue time).
func (it *Item) Clone() *Item {
	c := *it
	c.Affixes = append([]Affix(nil), it.Affixes...)
	c.Uniques = append([]string(nil), it.Uniques...)
	c.Sockets = append([]string(nil), it.Sockets...)
	c.Prov = append([]Prov(nil), it.Prov...)
	return &c
}

// DisplayName is what the UI shows.
func (it *Item) DisplayName() string {
	if it.Name != "" {
		return it.Name
	}
	if d := it.Def(); d != nil {
		return d.Name
	}
	return it.Base
}

// NewID returns a random uuid v4 string.
func NewID() string {
	var b [16]byte
	_, _ = rand.Read(b[:])
	b[6] = b[6]&0x0f | 0x40
	b[8] = b[8]&0x3f | 0x80
	h := hex.EncodeToString(b[:])
	return h[0:8] + "-" + h[8:12] + "-" + h[12:16] + "-" + h[16:20] + "-" + h[20:32]
}

// ---- DB column encodings (items.affixes / sockets / provenance jsonb) ----

// affixRow is one element of items.affixes: a stat line {"k","s","v"} or a
// unique {"u": key} (spec 11 keeps both in the affixes column).
type affixRow struct {
	K string  `json:"k,omitempty"`
	S string  `json:"s,omitempty"`
	V float64 `json:"v,omitempty"`
	U string  `json:"u,omitempty"`
}

// AffixesJSON is the items.affixes value.
func (it *Item) AffixesJSON() []byte {
	rows := make([]affixRow, 0, len(it.Affixes)+len(it.Uniques))
	for _, a := range it.Affixes {
		rows = append(rows, affixRow{K: a.Key, S: a.Stat, V: a.Value})
	}
	for _, u := range it.Uniques {
		rows = append(rows, affixRow{U: u})
	}
	b, _ := json.Marshal(rows)
	return b
}

// SetAffixesJSON parses items.affixes.
func (it *Item) SetAffixesJSON(b []byte) {
	var rows []affixRow
	_ = json.Unmarshal(b, &rows)
	it.Affixes, it.Uniques = nil, nil
	for _, r := range rows {
		if r.U != "" {
			it.Uniques = append(it.Uniques, r.U)
		} else if r.K != "" {
			it.Affixes = append(it.Affixes, Affix{Key: r.K, Stat: r.S, Value: r.V})
		}
	}
}

// SocketsJSON is items.sockets: an array of gem keys ("" = empty socket).
func (it *Item) SocketsJSON() []byte {
	s := it.Sockets
	if s == nil {
		s = []string{}
	}
	b, _ := json.Marshal(s)
	return b
}

// SetSocketsJSON parses items.sockets.
func (it *Item) SetSocketsJSON(b []byte) {
	it.Sockets = nil
	_ = json.Unmarshal(b, &it.Sockets)
}

// ProvJSON is items.provenance.
func (it *Item) ProvJSON() []byte {
	p := it.Prov
	if p == nil {
		p = []Prov{}
	}
	b, _ := json.Marshal(p)
	return b
}

// SetProvJSON parses items.provenance.
func (it *Item) SetProvJSON(b []byte) {
	it.Prov = nil
	_ = json.Unmarshal(b, &it.Prov)
}

// ---- wire (Event 400 inventory, contracts/events.md) ----

// WireItem is one item as the client sees it (JSON in Event 400's data).
type WireItem struct {
	H         uint32   `json:"h"`
	Base      string   `json:"b"`
	Qty       int      `json:"q"`
	Level     int      `json:"l"`
	Rarity    int      `json:"r"`
	Slot      string   `json:"s"`
	Name      string   `json:"n,omitempty"`
	Affixes   []Affix  `json:"a,omitempty"`
	Uniques   []string `json:"u,omitempty"`
	Sockets   []string `json:"k,omitempty"`
	Tradeable bool     `json:"t"`
	Verified  bool     `json:"v"`
	Hands     int      `json:"p"` // provenance entries (hands it passed through)
}

// Wire is the client view of an item.
func (it *Item) Wire() WireItem {
	return WireItem{H: it.H, Base: it.Base, Qty: it.Qty, Level: it.Level, Rarity: it.Rarity, Slot: it.Slot, Name: it.Name,
		Affixes: it.Affixes, Uniques: it.Uniques, Sockets: it.Sockets, Tradeable: it.Tradeable, Verified: it.Verified, Hands: len(it.Prov)}
}

