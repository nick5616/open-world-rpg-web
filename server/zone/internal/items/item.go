// Slot kinds.
const (
	PouchInv   = "inv"
	PouchGem   = "gem"
	PouchOre   = "ore"
	PouchPurse = "purse"
	Equip      = "eq"
)

// Equipment slots.
const (
	EqMain0 = "eq:main0"
	EqMain1 = "eq:main1"
	EqHead  = "eq:head"
	EqBody  = "eq:body"
	EqLegs  = "eq:legs"
)

// MainSlot is the equipment slot of a loadout's weapon.
func MainSlot(loadout int) string {
	if loadout == 1 {
		return EqMain1
	}
	return EqMain0
}

// SlotPouch splits "inv:12" into ("inv", 12); "purse" -> ("purse", 0);
// "eq:head" -> ("eq", -1).
func SlotPouch(slot string) (string, int) {
	p, rest, ok := strings.Cut(slot, ":")
	if !ok {
		return p, 0
	}
	n, err := strconv.Atoi(rest)
	if err != nil {
		return p, -1
	}
	return p, n
}

// IsEquipped reports an equipment slot.
func (it *Item) IsEquipped() bool { return strings.HasPrefix(it.Slot, "eq:") }
