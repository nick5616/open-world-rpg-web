// Golden scenarios: a ground function, a starting state and the scripted
// inputs. The ground functions are deliberately trivial (flat, tilted plane) so
// the Go replay can reproduce them in two lines.

import { FlatGround, PlaneGround, type GroundQuery } from '../ground';
import { stepMovement, STEP_DT, type MoveState } from '../movement';
import { goldenScript, type ScriptFrame } from './script';

export type GroundSpec = { kind: 'flat'; height: number } | { kind: 'plane'; base: number; sx: number; sz: number };

export interface Scenario {
  name: string;
  ground: GroundSpec;
  start: { x: number; z: number };
}

export const SCENARIOS: Scenario[] = [
  { name: 'flat', ground: { kind: 'flat', height: 0 }, start: { x: 2048, z: 2048 } },
  { name: 'plane', ground: { kind: 'plane', base: 10, sx: 0.15, sz: -0.08 }, start: { x: 100, z: 100 } },
];

export function makeGround(g: GroundSpec): GroundQuery {
  return g.kind === 'flat' ? new FlatGround(g.height) : new PlaneGround(g.base, g.sx, g.sz);
}

/** [x, y, z, vx, vy, vz, airJumps] after each step. */
export type StateRow = [number, number, number, number, number, number, number];

export interface GoldenFile {
  format: 'lodestone-movement-golden';
  version: 1;
  doc: string;
  scenario: string;
  dt: number;
  ground: GroundSpec;
  initial: StateRow;
  /** [seq, flags, yawU16, pitchI16] per step. */
  frames: [number, number, number, number][];
  /** State after applying frames[i]. */
  states: StateRow[];
}

export function toRow(s: MoveState): StateRow {
  return [s.pos.x, s.pos.y, s.pos.z, s.vel.x, s.vel.y, s.vel.z, s.airJumps];
}

export function initialState(sc: Scenario): MoveState {
  const ground = makeGround(sc.ground);
  return { pos: { x: sc.start.x, y: ground.heightAt(sc.start.x, sc.start.z), z: sc.start.z }, vel: { x: 0, y: 0, z: 0 }, airJumps: 0 };
}

export function runScenario(sc: Scenario, frames: ScriptFrame[] = goldenScript()): GoldenFile {
  const ground = makeGround(sc.ground);
  let s = initialState(sc);
  const initial = toRow(s);
  const states: StateRow[] = [];
  for (const f of frames) {
    s = stepMovement(s, f, ground, STEP_DT);
    states.push(toRow(s));
  }
  return {
    format: 'lodestone-movement-golden',
    version: 1,
    doc: 'Generated by client/src/sim/golden/generate.ts from stepMovement (client/src/sim/movement.ts). Replay: start at `initial`, apply each frame with dt, compare to states[i]. See client/src/sim/README.md.',
    scenario: sc.name,
    dt: STEP_DT,
    ground: sc.ground,
    initial,
    frames: frames.map((f) => [f.seq, f.flags, f.yaw, f.pitch]),
    states,
  };
}
