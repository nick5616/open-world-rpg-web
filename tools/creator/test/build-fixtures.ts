// Builds the shared normalize fixtures: every case in fixture-cases.ts with
// the TS normalizer's exact output. The Go endpoint's tests (internal/spec)
// load the written file (tools/creator/fixtures/normalize.json) and must
// produce the same specs and change lists, which is how "TS and Go clamp
// identically" is enforced. scripts/gen-fixtures.ts writes it.
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CASES, caseInput } from './fixture-cases';
import { normalize } from '../web/src/spec/normalize';

export const FIXTURE_FILE = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'fixtures', 'normalize.json');

export function buildFixtures() {
  return {
    _comment:
      'Generated by tools/creator/scripts/gen-fixtures.ts from test/fixture-cases.ts. Do not edit by hand. Error messages are not compared (ajv and the Go validator word them differently); only ok=false is.',
    cases: CASES.map((c) => {
      const input = caseInput(c);
      const r = normalize(input);
      return { name: c.name, input, expect: r.ok ? { ok: true, spec: r.spec, changes: r.changes } : { ok: false } };
    }),
  };
}

/** The file's exact text (2-space JSON + newline), so a test can diff it. */
export function fixtureText(): string {
  return JSON.stringify(buildFixtures(), null, 2) + '\n';
}
