import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
const port = 5291;
const vite = spawn(process.execPath, [process.cwd() + '/node_modules/vite/bin/vite.js', '--port', String(port), '--strictPort', '--host', '127.0.0.1'], { cwd: 'client', stdio: 'ignore' });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
for (let i = 0; i < 100; i++) { try { if ((await fetch(`http://127.0.0.1:${port}/`)).ok) break; } catch {} await sleep(300); }
const browser = await chromium.launch({ headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 960, height: 540 } });
page.on('console', (m) => console.log('console', m.type(), m.text()));
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.goto(`http://127.0.0.1:${port}/?debug=1&solo=1&ground=worldgen&spawn=1122,2340`, { waitUntil: 'networkidle' });
await page.click('[data-testid="play"]');
await page.waitForFunction(() => window.__lodestone?.player().pos.y > 50, null, { polling: 250, timeout: 60000 });
await page.evaluate(() => { window.__lodestone.setLook(Math.PI, -0.25); });
await sleep(1500);
await page.screenshot({ path: 'docs/evidence/tmp/t1.png' });
await page.evaluate(() => { window.__lodestone.setFly(true); window.__lodestone.teleport({ x: 1122, y: 355, z: 2341 }); });
await sleep(1500);
console.log(await page.evaluate(() => window.__lodestone.player()));
await page.screenshot({ path: 'docs/evidence/tmp/t2.png' });
await browser.close();
vite.kill();
process.exit(0);
