// Build steps shared by the real deploy and the local rehearsal (WP18):
// worldgen.wasm once, then every service image from that same file, then the
// static client and creator builds. Building the wasm on the host (not in a
// Docker stage) is deliberate: the zone, account and creator images and the
// client bundle must carry byte-identical worldgen.wasm, and spec 5 pins
// worlds to its content hash.
import fs from 'node:fs';
import path from 'node:path';
import { root } from '../../scripts/lib.mjs';

export const SERVICES = ['director', 'account', 'zone', 'social', 'creator'];

/** The five .dockerignore copies must stay identical (one whitelist). */
export function checkDockerignores() {
  const dir = path.join(root, 'infra', 'docker');
  const ref = fs.readFileSync(path.join(dir, 'zone.Dockerfile.dockerignore'), 'utf8');
  for (const s of SERVICES) {
    const f = path.join(dir, `${s}.Dockerfile.dockerignore`);
    if (fs.readFileSync(f, 'utf8') !== ref) throw new Error(`${f} differs from zone.Dockerfile.dockerignore; keep the whitelists identical`);
  }
}

export function wasmManifest() {
  const f = path.join(root, 'worldgen', 'pkg', 'manifest.json');
  return fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : null;
}

export function buildWasm(r) {
  r.section('worldgen.wasm (content-hashed)');
  r.run(['node', 'worldgen/scripts/build-wasm.mjs']);
  const m = r.dryRun ? null : wasmManifest();
  if (m) r.note(`worldgen ${m.file} sha256 ${m.sha256} genVersion ${m.genVersion}`);
  return m;
}

/** docker build every service; returns image refs by service. */
export function buildImages(r, { registry, tag, services = SERVICES }) {
  r.section(`container images (${registry}/<service>:${tag})`);
  checkDockerignores();
  const refs = {};
  for (const s of services) {
    const ref = `${registry}/${s}:${tag}`;
    r.run(['docker', 'build', '-f', `infra/docker/${s}.Dockerfile`, '--build-arg', `VERSION=${tag}`, '-t', ref, '.'], { env: { DOCKER_BUILDKIT: '1' } });
    refs[s] = ref;
  }
  return refs;
}

export function pushImages(r, refs) {
  r.section('push images to Artifact Registry');
  for (const ref of Object.values(refs)) r.run(['docker', 'push', ref]);
}

/** Production client build against the given endpoints. */
export function buildClient(r, viteEnv) {
  r.section('client build (static, for Netlify)');
  const shown = Object.entries(viteEnv)
    .filter(([, v]) => v)
    .map(([k, v]) => `${k}=${v}`)
    .join(' ');
  r.note(`env: ${shown}`);
  r.run(['npm', 'run', 'build', '-w', 'client'], { env: viteEnv });
  copyHeaders(r, 'client', path.join(root, 'client', 'dist'));
}

export function buildCreator(r) {
  r.section('creator web build (static, for Netlify)');
  r.run(['npm', 'run', 'build', '-w', '@lodestone/creator']);
  copyHeaders(r, 'creator', path.join(root, 'tools', 'creator', 'dist'));
}

function copyHeaders(r, which, dist) {
  const src = path.join(root, 'infra', 'netlify', `${which}._headers`);
  r.note(`copy infra/netlify/${which}._headers -> ${path.relative(root, dist)}/_headers`);
  if (!r.dryRun) fs.copyFileSync(src, path.join(dist, '_headers'));
}

export function writeCreatorRedirects(r, creatorUrl) {
  const dist = path.join(root, 'tools', 'creator', 'dist');
  const body = `# Generated by infra/deploy.mjs: the creator page calls same-origin /v1, proxied to Cloud Run.\n/v1/*  ${creatorUrl}/v1/:splat  200\n`;
  r.note(`write tools/creator/dist/_redirects: /v1/* -> ${creatorUrl}/v1/:splat (200 proxy)`);
  if (!r.dryRun) fs.writeFileSync(path.join(dist, '_redirects'), body);
}
