// Shared helpers for the contract code generators.
import { spawnSync } from 'node:child_process';

export const HEADER_NOTE = 'Code generated by contracts/codegen. DO NOT EDIT.';

export const pascal = (s) =>
  s
    .split(/[_\s-]+/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('');

export const camelToPascal = (s) => s[0].toUpperCase() + s.slice(1);

/** Go identifier for a camelCase field: id -> ID, entityId -> EntityID, url -> URL. */
export function goField(s) {
  const p = camelToPascal(s);
  return p.replace(/Id(?=[A-Z]|$)/g, 'ID').replace(/^Url$/, 'URL').replace(/Url(?=[A-Z]|$)/g, 'URL');
}

/** UPPER_SNAKE -> PascalCase (Go constant names). */
export const snakeToPascal = (s) =>
  s
    .toLowerCase()
    .split('_')
    .map((p) => (p ? p[0].toUpperCase() + p.slice(1) : ''))
    .join('');

/** Pipe Go source through gofmt so generated files are canonical (and --check is stable). */
export function gofmt(src) {
  const r = spawnSync('gofmt', [], { input: src, encoding: 'utf8' });
  if (r.error) throw new Error(`gofmt not found on PATH (install Go): ${r.error.message}`);
  if (r.status !== 0) throw new Error(`gofmt failed:\n${r.stderr}\n----\n${src}`);
  return r.stdout;
}

/** Deterministic PRNG (mulberry32) so golden vectors are stable across runs and machines. */
export function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function strHash(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}
